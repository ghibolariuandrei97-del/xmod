-- self test for lib/metalog.lua and lib/translator.lua (run by test/run_libs.sh in the mock engine)
local pass, fail = 0, 0
local function ok(c, what) if c then pass = pass + 1 else fail = fail + 1; print("LIBTEST FAIL " .. what) end end
local ML = require("metalog")
local T = require("translator")
local MODE = (xmod.fs.read("data/libtest_mode.txt") or "normal"):match("%a+")

local function run()
  local date = os.date("%Y-%m-%d")
  if MODE == "disabled" then
    local L = ML.new("libtest")
    ok(L.info == ML.NOOP and L.debug == ML.NOOP and L.error == ML.NOOP and L.dump == ML.NOOP, "disabled: methods are empty")
    ok(L:fn(function() return 1 end) == ML.NOOP, "disabled: fn() returns empty")
    ok(ML.debug_only(print) == ML.NOOP, "disabled: debug_only empty")
    local okc, e = L:try(function() error("x") end); ok(okc == false and tostring(e):find("x"), "disabled: try still pcalls")
    local f = function(a) return a * 2 end; ok(L:wrap(f) == f, "disabled: wrap returns fn")
    ok(L:assert(5) == 5, "disabled: assert returns value")
    L:info("must not be written"); L:error("must not be written"); ML.flush_all()
    ok(not xmod.fs.exists("data/logs/libtest_" .. date .. ".md"), "disabled: no file")
    print(("LIBTEST DONE: %d passed, %d failed"):format(pass, fail)); return
  end
  if MODE == "nodir" then
    local L = ML.new("libtest")
    L:warn("fallback warning"); ML.flush_all()
    local s = xmod.fs.read("data/logs_libtest_" .. date .. ".md")
    ok(s and s:find("fallback warning", 1, true), "nodir: fallback file data/logs_libtest_*.md")
    local sid = xmod.player.steamid(1)
    print("LIBTEST steamid of player 1: " .. tostring(sid) .. ", lang " .. T.lang(1))
    if tostring(sid):match("^STEAM_%d:%d:%d+$") then ok(T.lang(1) == "ro", "language choice persisted (vault)") end
    print(("LIBTEST DONE: %d passed, %d failed"):format(pass, fail)); return
  end

  -- ================= metalog
  local L = ML.new("libtest", { level = "trace" })
  ok(ML.where(1):find("libs_test.lua:%d+$"), "where() gives file:line: " .. ML.where(1))
  ML.new(); ok(ML.get("libs_test") ~= nil, "new() without name uses the file name")
  ok(ML.format("%d-%s", 3, "a") == "3-a", "format")
  ok(ML.format("%d", "notanumber"):find("notanumber"), "bad format does not raise")
  ok(ML.format("t=%s", { 1, 2 }):find("{ 1, 2 }", 1, true), "table arg dumped")
  local cyc = { a = 1 }; cyc.self = cyc
  ok(ML.dump(cyc):find("<cycle>"), "dump marks cycles")
  ok(ML.dump({ x = { y = { z = { w = { v = 1 } } } } }, 2):find("{...}", 1, true), "dump depth limit")
  ok(ML.who(1):find("Tester") and ML.who(0) == "SERVER" and ML.who(31):find("not connected"), "who()")
  L:trace("trace %d", 1); L:debug("debug"); L:info("info line"); L:warn("warn line"); L:error("error line")
  L:info("multi\nline\ntext")
  L:dump("tbl", { a = 1, b = { 2, 3 } })
  L:table("tab", { "id", "name" }, { { 1, "a|b" }, { id = 2, name = "c" } })
  L:section("Section X")
  for _ = 1, 3 do L:once("info", "only once %s", "!") end
  for _ = 1, 5 do L:every(100, "info", "rate %s", "limited") end
  L:time("t"); local ms = L:time_end("t"); ok(type(ms) == "number", "time_end returns ms")
  ok(L:count("c") == 1 and L:count("c", 2) == 3, "count")
  L:counts()
  L:player(1, "test player")
  local okc, e = L:try(function(a, b) error("boom " .. a) end, "A", { 1 }); ok(okc == false and tostring(e):find("boom A"), "try returns false, err")
  local r1, r2 = select(2, L:try(function() return 1, 2 end)); ok(r1 == 1 and r2 == 2, "try returns results")
  local w = L:wrap(function(x) if x == 0 then error("zero!") end return 10 / x end, "divider")
  ok(w(2) == 5 and w(0) == nil, "wrap: result / nil on error")
  ok(L:assert(false, "assert %d", 7) == false, "assert returns cond")
  local mod = L:trace_calls({ add = function(a, b) return a + b end }, "mod")
  ok(mod.add(2, 3) == 5, "trace_calls keeps behaviour")
  ok(L:fn(print) == print, "fn() keeps function when on")
  L:bench("b", 100, function() end)
  -- levels
  local Q = ML.new("libtest_quiet", { level = "warn" })
  ok(Q.info == ML.NOOP and Q.debug == ML.NOOP and Q.warn ~= ML.NOOP and Q.dump == ML.NOOP, "level warn: info/debug empty")
  ok(Q:fn(print) == ML.NOOP and Q:fn(print, "error") == print, "fn by level")
  Q:set_level("trace"); ok(Q.trace ~= ML.NOOP, "set_level rebinds")
  ML.set_enabled(false); ok(L.info == ML.NOOP and Q.error == ML.NOOP, "runtime off")
  ML.set_enabled(true); ok(L.info ~= ML.NOOP, "runtime on")
  ML.flush_all()
  local s = xmod.fs.read("data/logs/libtest_" .. date .. ".md") or ""
  ok(s:find("^# metalog %- libtest"), "md header")
  ok(s:find("## %d+:%d+:%d+ %- map"), "map section")
  ok(s:find("**TRACE** `plugins/libs_test.lua:", 1, true), "trace line with location")
  ok(s:find("**ERROR**", 1, true) and s:find("error line", 1, true), "error line")
  ok(s:find("  ```\n  line\n  text\n  ```", 1, true), "multi-line block")
  ok(s:find("| 1 | a\\|b |", 1, true) and s:find("| 2 | c |", 1, true), "md table with escaped pipe")
  ok(s:find("### Section X", 1, true), "section")
  local _, n1 = s:gsub("only once !", ""); ok(n1 == 1, "once")
  local _, n2 = s:gsub("rate limited", ""); ok(n2 == 1, "every")
  ok(s:find("boom A", 1, true) and s:find("arguments: \"A\", {...}", 1, true) or s:find("arguments: \"A\"", 1, true), "try logs arguments")
  ok(s:find("divider: ", 1, true), "wrap label")
  ok(s:find("assertion failed: assert 7", 1, true), "assert line")
  ok(s:find("mod.add(2, 3) -> 5", 1, true), "trace_calls line")
  ok(s:find("bench b: 100 calls", 1, true), "bench")
  ok(s:find("| c | 3 |", 1, true), "counts table")
  ok(not s:find("must not", 1, true), "nothing while off")
  local e2 = xmod.fs.read("data/logs/errors_" .. date .. ".md") or ""
  ok(e2:find("[libtest]", 1, true) and e2:find("warn line", 1, true) and not e2:find("info line", 1, true), "combined errors file")

  -- ================= translator
  local langs, count, problems = T.parse("\239\187\191; c\n[en]\nA = Hello %s^nnext\nB=x\n[RO]\nA = Salut %s\nM:\nline1\nline2\n:\nbad line\n[123]\n")
  ok(langs.en.A == "Hello %s\nnext" and langs.en.B == "x" and langs.ro.A == "Salut %s", "parse basic + ^n + section case")
  ok(langs.ro.M == "line1\nline2", "multi-line block")
  ok(count == 4 and #problems == 2, "parse count/problems " .. count .. "/" .. #problems)
  ok(T.code("pt-BR") == "pt_br" and T.code("EN") == "en" and T.code("x") == nil, "code()")
  ok(T.format("%s=%d", "a", 3) == "a=3" and T.format("%d", "zz"):find("zz"), "format positional / safe")
  ok(T.format("{g}{name} {y}{n}", { name = "Bob", n = 3 }) == "{g}Bob {y}3", "named placeholders keep colour codes")
  local tr = T.new("libtest"):add("en", { HI = "hi %s", ONLY_EN = "en only", K_ONE = "%d kill", K = "%d kills" })
    :add("ro", { HI = "salut %s", K_ONE = "%d kill", K_FEW = "%d kill-uri", K_MANY = "%d de kill-uri" })
  ok(T.lang(1) == "en", "default language = xmod_language")
  ok(tr(1, "HI", "x") == "hi x", "__call")
  local changed
  xmod.on("lang_changed", function(id, old, new) changed = { id, old, new } end)
  ok(T.set_lang(1, "RO"), "set_lang"); ok(T.lang(1) == "ro" and changed and changed[2] == "en" and changed[3] == "ro", "lang_changed event")
  ok(tr(1, "HI", "x") == "salut x" and tr:get(2, "HI", "y") == "hi y", "per player")
  ok(tr(1, "ONLY_EN") == "en only", "fallback to en")
  ok(tr(1, "NOPE") == "NOPE", "missing key -> key")
  ok(tr:plural(1, "K", 1) == "1 kill" and tr:plural(1, "K", 5) == "5 kill-uri" and tr:plural(1, "K", 20) == "20 de kill-uri"
     and tr:plural(1, "K", 101) == "101 kill-uri", "plural ro")
  ok(tr:plural(2, "K", 1) == "1 kill" and tr:plural(2, "K", 2) == "2 kills", "plural en")
  ok(T.plural_form("ru", 21) == "ONE" and T.plural_form("ru", 23) == "FEW" and T.plural_form("ru", 11) == "MANY", "plural ru")
  ok(tr:in_lang("de", "HI", "z") == "hi z", "unknown lang -> server/en")
  xmod.cvar.set("xmod_language", "ro"); ok(tr(2, "HI", "q") == "salut q", "server language cvar"); xmod.cvar.set("xmod_language", "en")
  ok(T.common(1, "YES") == "Da" and T.common(2, "YES") == "Yes", "common dictionary")
  ok(T.t(1, "K_FEW", 3) == "3 kill-uri" and T.t(1, "NO") == "Nu", "T.t global search")
  local miss = tr:missing(); ok(miss.ro and miss.ro[1] == "K" and miss.ro[2] == "ONLY_EN", "missing()")
  local found = false; for _, l in ipairs(T.languages()) do if l.code == "ru" then found = true end end; ok(found, "languages() from common.txt")
  tr:chat(0, "HI", "all"); tr:print(1, "center", "HI", "c"); tr:hud(0, { y = 0.3 }, "HI", "h"); tr:console(0, "HI", "srv")
  ok(T.menu(1), "menu opens")
  local demo = T.load("translator_demo"); ok(demo:has("DEMO_HP", "ro") and demo:plural(1, "DEMO_KILLS", 20):find("de kill"), "demo dictionary")
  T.reset_lang(1); ok(T.lang(1) == "en", "reset_lang")
  T.set_lang(1, "ro")
  print(("LIBTEST DONE: %d passed, %d failed"):format(pass, fail))
end
xmod.timer.after(1, function() local s, e = pcall(run); if not s then print("LIBTEST FAIL crashed: " .. tostring(e)) end end)
