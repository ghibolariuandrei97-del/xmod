#!/usr/bin/env python3
"""Generates offsets.inc (private-data member table) from AMX Mod X gamedata (cstrike).
usage: gen_offsets.py <amxmodx>/gamedata/common.games  > offsets.inc"""
import re, sys, os, glob
root = sys.argv[1]
T = {'integer':'PT_INT','float':'PT_FLOAT','boolean':'PT_BOOL','short':'PT_SHORT','character':'PT_CHAR','classptr':'PT_CBASE',
     'ehandle':'PT_EHANDLE','edict':'PT_EDICT','entvars':'PT_ENTVARS','vector':'PT_VECTOR','string':'PT_STRING','stringint':'PT_STRINGINT'}
def parse(path):
    t = open(path, encoding='latin-1').read()
    cm = re.search(r'"Classes"\s*\{\s*"(\w+)"', t)
    cls = cm.group(1) if cm else os.path.basename(path)
    out = []
    for m in re.finditer(r'"(\w+)"\s*(?://[^\n]*)?\s*\{([^{}]*)\}', t):
        b = m.group(2); g = lambda k: (re.search(r'"%s"\s*"([^"]+)"' % k, b) or [None, None])[1]
        ty, w, l = g('type'), g('windows'), g('linux')
        if ty not in T or w is None or l is None: continue
        size = int(g('size') or 1); uns = g('unsigned') == '1'
        out.append((cls, m.group(1), T[ty], size, int(w), int(l), uns))
    return out
rows = []
for f in sorted(glob.glob(os.path.join(root, 'entities.games/cstrike/*.txt'))): rows += parse(f)
rules = []
for f in ['gamerules.games/cstrike/offsets-cgamerules.txt', 'gamerules.games/cstrike/offsets-chalflifemultiplay.txt']: rules += parse(os.path.join(root, f))
print('// GENERATED by tools/gen_offsets.py from AMX Mod X gamedata (cstrike) - byte offsets {class, member, type, count, windows, linux, unsigned}')
print('// entity private data (CBaseEntity and subclasses)')
print('#ifdef MC_PDATA_ROW')
for r in rows: print('MC_PDATA_ROW("%s", "%s", %s, %d, %d, %d, %d)' % (r[0], r[1], r[2], r[3], r[4], r[5], int(r[6])))
print('#endif')
print('#ifdef MC_RULES_ROW')
for r in rules: print('MC_RULES_ROW("%s", "%s", %s, %d, %d, %d, %d)' % (r[0], r[1], r[2], r[3], r[4], r[5], int(r[6])))
print('#endif')
sys.stderr.write('%d entity members, %d gamerules members\n' % (len(rows), len(rules)))
