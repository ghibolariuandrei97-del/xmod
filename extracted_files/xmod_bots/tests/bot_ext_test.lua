xmod.register("bot_ext_test", "1", "test")
local pass, fail = 0, 0
local function ok(c, what) if c then pass = pass + 1 else fail = fail + 1; xmod.log("BOTTEST FAIL " .. what) end end
xmod.timer.after(2, function()
  local B = xmod.bot
  ok(xmod.ext.available("bot"), "namespace bot available")
  ok(xmod.ext.available("bot", "nav_path"), "bot.nav_path")
  ok(B.count() == 0 and #B.list() == 0, "no bots yet")
  ok(B.is_bot(1) == false, "player 1 is not our bot")
  ok(B.weapon(1) == nil, "weapon nil without active item")
  B.config({ autolearn = false, max_nodes = 500, danger_weight = 1.5, path_random = 0 })
  B.nav_clear()
  local a = B.nav_add(0, 0, 36, 4); local b = B.nav_add(64, 0, 36); local c = B.nav_add(128, 0, 36, 8)
  ok(a == 1 and b == 2 and c == 3, "nav_add 1-based")
  ok(B.nav_link(a, b, 0, true) and B.nav_link(b, c, 1, true), "nav_link")
  local p = B.nav_path(a, c, 1)
  ok(p and #p == 3 and p[1] == 1 and p[3] == 3, "nav_path")
  local n = B.nav_node(c)
  ok(n and n.x == 128 and n.flags == 8 and #n.links == 1 and n.links[1].to == 2, "nav_node")
  ok(#B.nav_find(8) == 1 and B.nav_find(8)[1] == 3, "nav_find")
  ok(B.nav_nearest(60, 5, 36, 100) == 2, "nav_nearest")
  B.nav_learn(128, 0, 36, 2, "death", 2)
  ok(B.nav_node(3).danger_ct > 0.4, "nav_learn")
  ok(B.nav_save() == true, "nav_save")
  B.nav_clear(); ok(B.nav_info().nodes == 0, "nav_clear")
  ok(B.nav_load() == true and B.nav_info().nodes == 3, "nav_load")
  ok(type(B.add) == "function", "add exists")
  local okc, err = pcall(B.go, 1, 0, 0, 0)
  ok(not okc and tostring(err):find("not a bot"), "go on a non-bot raises")
  ok(xmod.has_export("xbots.add") and xmod.call("xbots.is_bot", 1) == false, "xbots brain loaded")
  xmod.log(string.format("BOTTEST DONE: %d passed, %d failed", pass, fail))
end)
