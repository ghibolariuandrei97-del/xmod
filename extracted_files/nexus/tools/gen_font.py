#!/usr/bin/env python3
"""Builds client/font_data.h: an alpha-only glyph atlas (RLE packed) + metrics from DejaVu Sans Bold.
Glyphs: ASCII, Latin-1, Latin Extended-A (Romanian, Polish, Czech, Turkish ...), Cyrillic, a few symbols.  Needs Pillow."""
import os, sys
from PIL import Image, ImageDraw, ImageFont
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ttf = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
SIZE, W = 26, 1024
font = ImageFont.truetype(ttf, SIZE)
cps = list(range(32, 127)) + list(range(161, 384)) + [0x218, 0x219, 0x21A, 0x21B] + list(range(0x400, 0x460)) + \
      [0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2026, 0x20AC, 0x2190, 0x2191, 0x2192, 0x2193, 0x2605, 0x2665, 0x2713, 0x2717, 0x25A0, 0x25B2, 0x25BC, 0x25CF]
ascent, descent = font.getmetrics(); line_h = ascent + descent
x = y = 1; row_h = 0; glyphs = []; H = 1024
atlas = Image.new("L", (W, H), 0); draw = ImageDraw.Draw(atlas)
for cp in cps:
    ch = chr(cp); bbox = font.getbbox(ch); adv = font.getlength(ch)
    gw, gh = max(0, bbox[2] - bbox[0]), max(0, bbox[3] - bbox[1])
    if x + gw + 2 > W: x = 1; y += row_h + 2; row_h = 0
    if gw and gh: draw.text((x - bbox[0], y - bbox[1]), ch, font=font, fill=255)
    glyphs.append((cp, x, y, gw, gh, bbox[0], bbox[1], int(round(adv)))); x += gw + 2; row_h = max(row_h, gh)
used_h = y + row_h + 2; H2 = 1
while H2 < used_h: H2 *= 2
atlas = atlas.crop((0, 0, W, H2)); data = atlas.tobytes()
out = bytearray(); i = 0                      # RLE: (count 1..255, value)
while i < len(data):
    v = data[i]; n = 1
    while i + n < len(data) and data[i + n] == v and n < 255: n += 1
    out += bytes((n, v)); i += n
with open(os.path.join(root, "client/font_data.h"), "w") as f:
    f.write("// GENERATED by tools/gen_font.py from DejaVu Sans Bold (Bitstream Vera / DejaVu licence: free to embed and redistribute)\n")
    f.write(f"#define NXF_W {W}\n#define NXF_H {H2}\n#define NXF_SIZE {SIZE}\n#define NXF_LINE {line_h}\n#define NXF_ASCENT {ascent}\n")
    f.write("struct NxGlyph { unsigned short cp, x, y; unsigned char w, h; signed char xo, yo; unsigned char adv; };\n")
    f.write("static const NxGlyph nxf_glyphs[] = {\n" + "".join(f"{{{c},{gx},{gy},{gw},{gh},{xo},{yo},{adv}}},\n" for c, gx, gy, gw, gh, xo, yo, adv in glyphs) + "};\n")
    f.write(f"static const unsigned int nxf_rle_len = {len(out)};\nstatic const unsigned char nxf_rle[] = {{\n")
    for k in range(0, len(out), 32): f.write(",".join(str(b) for b in out[k:k + 32]) + ",\n")
    f.write("};\n")
print(f"{len(glyphs)} glyphs, atlas {W}x{H2}, rle {len(out)} bytes, line {line_h}")
atlas.save("/tmp/claude-0/nexus_atlas.png")
