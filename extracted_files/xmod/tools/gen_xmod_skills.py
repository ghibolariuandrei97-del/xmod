#!/usr/bin/env python3
"""Builds xmod_skills.md (the single knowledge file) from tools/xmod_skills/*.md + generated appendices + the default configs.
Run after tools/gen_reapi.py / tools/gen_ham.py, and after changing any part. Appendix C (index) is regenerated by dumping the
live Lua table in the test host (see nexus/test) - update tools/xmod_skills/appendix_c_index.md when functions are added."""
import os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rd = lambda p: open(os.path.join(root, p), encoding="utf-8").read().rstrip() + "\n"
def section(path, title):
    t = rd(path).split("\n")
    return "\n## " + title + "\n" + "\n".join(t[1:]).strip() + "\n"
parts = [rd("tools/xmod_skills/1_core.md"), rd("tools/xmod_skills/2_nexus.md"), rd("tools/xmod_skills/3_extensions.md"), "\n# Appendices\n"]
parts.append(section("docs/REAPI_HOOKS.md", "Appendix A — ReAPI hookchains (event `reapi:<Hook>[:post]`)"))
parts.append(section("docs/HAM_FUNCTIONS.md", "Appendix B — Ham functions (event `ham:<func>:<classname>[:post]`)"))
parts.append("\n" + rd("tools/xmod_skills/appendix_c_index.md"))
cfg = ["\n## Appendix D — The default configuration files (`addons/xmod/configs/`)\n"]
for f in ["xmod.cfg", "plugins.ini", "extensions.ini", "users.ini", "query.ini", "maps.ini", "ads.ini", "xmod_debug.cfg"]:
    cfg.append("### `%s`\n```\n%s```\n" % (f, rd("addons/xmod/configs/" + f)))
parts.append("\n".join(cfg))
out = "\n".join(parts)
open(os.path.join(root, "xmod_skills.md"), "w", encoding="utf-8").write(out)
print("xmod_skills.md:", len(out), "bytes")
