#!/usr/bin/env python3
"""Generates src/ham_list.inc from tools/ham_cstrike.json (virtual indices + signatures taken from AMX Mod X's CS gamedata / HamSandwich)."""
import json, os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rows = json.load(open(os.path.join(root, "tools/ham_cstrike.json")))
T = {  # Ham signature -> (ret, [args]);  Vector-by-value / out-pointer signatures are intentionally unsupported
 "Void_Void": ("void", []), "Void_Int": ("void", ["int"]), "Void_Cbase": ("void", ["HamCbase*"]), "Void_Entvar": ("void", ["entvars_t*"]),
 "Void_Entvar_Int": ("void", ["entvars_t*", "int"]), "Void_Int_Int": ("void", ["int", "int"]),
 "Void_Cbase_Cbase_Int_Float": ("void", ["HamCbase*", "HamCbase*", "int", "float"]),
 "Int_Void": ("int", []), "Int_Int": ("int", ["int"]), "Int_Cbase": ("int", ["HamCbase*"]), "Int_Entvar": ("int", ["entvars_t*"]),
 "Int_Float_Int": ("int", ["float", "int"]), "Int_Entvar_Entvar_Float_Int": ("int", ["entvars_t*", "entvars_t*", "float", "int"]),
 "Int_Int_Str_Int": ("int", ["int", "const char*", "int"]), "Float_Void": ("float", []), "Float_Int": ("float", ["int"]),
 "Cbase_Void": ("HamCbase*", []), "Str_Void": ("const char*", []),
}
out = ["// GENERATED by tools/gen_ham.py"]
skipped = []
for r in rows:
    n = r["name"]
    if n.startswith(("dod_", "tfc_", "ts_", "esf_", "ns_", "svencoop_")): continue
    if r["sig"] not in T: skipped.append(n); continue
    ret, args = T[r["sig"]]
    out.append("HAM(%s, %d, %d, %s%s)" % (n, r["win"], r["lin"], ret, "".join(", " + a for a in args)))
open(os.path.join(root, "src/ham_list.inc"), "w").write("\n".join(out) + "\n")
print(len(out) - 1, "ham functions; skipped (unsupported signatures):", ", ".join(skipped))

lines = ["# Ham hooks available to xmod (CS 1.6 virtual functions)", "", "Use `xmod.on(\"ham:<func>:<classname>\", fn)` / `...:post`. Examples of classnames: `player`, `weapon_ak47`, `func_door`, `info_target`.",
 "The first arg of `fn` is always the entity (`this`); then the args below. Pre-hooks may return `xmod.HC_SUPERCEDE, value`; `xmod.hook.set_arg(n, v)` changes numeric args (n counts after `this`). Post hooks get the return value as extra last arg.", "",
 "| Function | Args | Returns |", "|---|---|---|"]
def k(t): return {"int": "int", "float": "float", "entvars_t*": "ent", "HamCbase*": "ent", "const char*": "string", "void": "-"}[t]
for r in rows:
    n = r["name"]
    if n.startswith(("dod_", "tfc_", "ts_", "esf_")) or r["sig"] not in T: continue
    ret, args = T[r["sig"]]
    lines.append("| `%s` | %s | %s |" % (n, ", ".join(k(a) for a in args) or "-", k(ret)))
open(os.path.join(root, "docs/HAM_FUNCTIONS.md"), "w").write("\n".join(lines) + "\n")
