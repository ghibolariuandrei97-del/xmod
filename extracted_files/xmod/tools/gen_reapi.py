#!/usr/bin/env python3
"""Generates src/reapi_decl.h + src/reapi_list.inc from ReGameDLL's public regamedll_api.h.
Usage: python3 tools/gen_reapi.py [path/to/regamedll_api.h]   (default: deps/regamedll/regamedll/public/regamedll/regamedll_api.h)
Re-run after updating deps/regamedll to pick up newly added hookchains."""
import re, sys, os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, "deps/regamedll/regamedll/public/regamedll/regamedll_api.h")
txt = open(src, encoding="utf-8", errors="replace").read().replace("\r", "")
typedefs = re.findall(r"^typedef IHookChain(?:Registry)?(?:Class)?<.*?> IReGame\w+;$", txt, re.M)
hooks = re.findall(r"^typedef IHookChain(?:Class)?<.*?> IReGameHook_(\w+);$", txt, re.M)
def block(start_pat):
    m = re.search(start_pat, txt, re.M); i = m.start(); j = txt.index("\n};", i) + 3
    return txt[i:j]
chains = block(r"^class IReGameHookchains \{")
api = block(r"^class IReGameApi \{")
chains = chains.replace("virtual ~IReGameHookchains() {}", "REAPI_VDTOR(IReGameHookchains)")
api = api.replace("virtual ~IReGameApi() {}", "REAPI_VDTOR(IReGameApi)")
body = "\n".join(typedefs) + "\n\n" + chains + "\n\n" + api + "\n"
body = body.replace("struct TraceResult", "TraceResult")
classes = sorted(set(re.findall(r"\bC[A-Z][A-Za-z0-9_]*\b", body)))
structs = sorted((set(re.findall(r"\bstruct\s+([A-Za-z_]\w*)", body)) | {"ReGameFuncs_t"}) - {"entvars_s", "edict_s", "TraceResult"})
enums = ["WeaponIdType","TeamName","ScenarioEventEndRound","RewardType","PLAYER_ANIM","ItemRestType","ItemID","GameEventType","AmmoType","hash_types_e"]
ent_classes = [c for c in classes if c not in ("CGameRules", "CHalfLifeMultiplay")]
out = ["// GENERATED by tools/gen_reapi.py from ReGameDLL regamedll_api.h - do not edit",
"#pragma once", "// Standalone re-declaration of the ReGameDLL hookchain ABI (no cssdk needed).",
"#ifdef _WIN32", "  // MSVC vtables have ONE slot for a virtual destructor, Itanium (GCC) has two: use a plain virtual slot on Windows.",
"  #define REAPI_VDTOR(C) virtual void _vdtor_slot_##C() {}", "  #define REAPI_PROT_VDTOR(C) virtual void _vdtor_slot_##C() {}",
"#else", "  #define REAPI_VDTOR(C) virtual ~C() {}", "  #define REAPI_PROT_VDTOR(C) virtual ~C() {}", "#endif",
"typedef float vec_t;",
"template<typename t_ret, typename ...t_args> class IHookChain { protected: REAPI_PROT_VDTOR(IHookChain) public:",
"  virtual t_ret callNext(t_args... args) = 0; virtual t_ret callOriginal(t_args... args) = 0; };",
"template<typename t_ret, typename t_class, typename ...t_args> class IHookChainClass { protected: REAPI_PROT_VDTOR(IHookChainClass) public:",
"  virtual t_ret callNext(t_class *, t_args... args) = 0; virtual t_ret callOriginal(t_class *, t_args... args) = 0; };",
"enum HookChainPriority { HC_PRIORITY_UNINTERRUPTABLE = 255, HC_PRIORITY_HIGH = 192, HC_PRIORITY_DEFAULT = 128, HC_PRIORITY_MEDIUM = 64, HC_PRIORITY_LOW = 0 };",
"template<typename t_ret, typename ...t_args> class IHookChainRegistry { public:",
"  typedef t_ret(*hookfunc_t)(IHookChain<t_ret, t_args...>*, t_args...);",
"  virtual void registerHook(hookfunc_t hook, int priority = HC_PRIORITY_DEFAULT) = 0; virtual void unregisterHook(hookfunc_t hook) = 0; };",
"template<typename t_ret, typename t_class, typename ...t_args> class IHookChainRegistryClass { public:",
"  typedef t_ret(*hookfunc_t)(IHookChainClass<t_ret, t_class, t_args...>*, t_class *, t_args...);",
"  virtual void registerHook(hookfunc_t hook, int priority = HC_PRIORITY_DEFAULT) = 0; virtual void unregisterHook(hookfunc_t hook) = 0; };",
""]
out += [f"class {c};" for c in classes]
out += [f"struct {s};" for s in structs]
out += [f"enum {e} : int {{}};" for e in enums]
out += ["", body, "template<class T> struct is_ent;  // specialised below (entity classes: pev lives right after the vptr)"]
out += [f"template<> struct is_ent<{c}> : std::true_type {{}};" for c in ent_classes]
open(os.path.join(root, "src/reapi_decl.h"), "w").write("\n".join(out) + "\n")
open(os.path.join(root, "src/reapi_list.inc"), "w").write("// GENERATED by tools/gen_reapi.py\n" + "\n".join(f"RG_HOOK({h})" for h in hooks) + "\n")
print(len(hooks), "hooks;", len(classes), "classes;", len(structs), "structs")

# ---- docs/REAPI_HOOKS.md (Lua-facing view of every hook)
def lua_kind(t):
    t = t.replace("class ", "").replace("struct ", "").strip()
    base = t.replace("&", "").replace("*", "").strip()
    if t.endswith("*"):
        if base in ("char", "const char"): return "string"
        if base in ("entvars_t", "entvars_s", "edict_t", "edict_s") or (base.startswith("C") and base not in ("CGameRules",)): return "ent"
        return "nil"
    if base == "Vector": return "vec{x,y,z}"
    if base in ("float", "double"): return "float"
    return "int"
rows = []
for m in re.finditer(r"^typedef (IHookChain(?:Class)?)<(.*?)> IReGameHook_(\w+);$", txt, re.M):
    kind, args, name = m.groups(); a = [x.strip() for x in args.split(",")]
    ret = a[0]; rest = a[1:]
    if kind == "IHookChainClass": self_arg = ["this:ent"]; rest = rest[1:]
    else: self_arg = []
    desc = ", ".join(self_arg + [f"{lua_kind(x)}" + ("(mod)" if "&" in x and "Vector" not in x else "") for x in rest])
    rr = "-" if ret == "void" else lua_kind(ret)
    rows.append(f"| `{name}` | {desc or '-'} | {rr} |")
open(os.path.join(root, "docs/REAPI_HOOKS.md"), "w").write("# ReAPI hookchains available to xmod (ReGameDLL required)\n\nUse `xmod.on(\"reapi:<Name>\", fn)` / `xmod.on(\"reapi:<Name>:post\", fn)`.\nArgs are passed to `fn` in order; `(mod)` args can be changed with `xmod.hook.set_arg(n, value)` (n counts after `this`). Return `xmod.HC_SUPERCEDE, value` to skip the original. Post hooks get the return value as an extra last arg.\n\n| Hook | Args | Returns |\n|---|---|---|\n" + "\n".join(rows) + "\n")
print("docs written")
